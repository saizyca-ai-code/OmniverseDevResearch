#!/usr/bin/env python3
"""Build a deterministic Markdown index from research front matter."""
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]
SEARCH_DIRS = (ROOT / "docs" / "research", ROOT / "experiments")
OUTPUT = ROOT / "docs" / "GENERATED-RESEARCH-INDEX.md"


def load_doc(path):
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        return None
    parts = text.split("---", 2)
    if len(parts) < 3:
        return None
    try:
        data = yaml.safe_load(parts[1])
    except yaml.YAMLError:
        return None
    if not isinstance(data, dict) or not data.get("id"):
        return None
    return data


def main():
    rows = []
    for directory in SEARCH_DIRS:
        if directory.exists():
            for path in directory.rglob("*.md"):
                if path.name.lower() == "readme.md":
                    continue
                data = load_doc(path)
                if data:
                    rel = path.relative_to(ROOT).as_posix()
                    title = str(data.get("title", path.stem)).replace("|", "\\|")
                    rows.append((str(data.get("id")), title, str(data.get("type", "")),
                                 str(data.get("status", "")), rel))
    rows.sort(key=lambda row: (row[0], row[4]))
    lines = [
        "<!-- Generated by scripts/build_index.py. Do not edit manually. -->",
        "# Generated Research Index", "",
        f"Documents indexed: {len(rows)}", "",
        "| ID | Title | Type | Status | Path |",
        "|---|---|---|---|---|",
    ]
    for doc_id, title, doc_type, status, path in rows:
        link = Path(path).relative_to("docs").as_posix() if path.startswith("docs/") else "../" + path
        lines.append(f"| {doc_id} | {title} | {doc_type} | {status} | [{path}]({link}) |")
    lines.append("")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(rows)} entries).")


if __name__ == "__main__":
    main()
